export function normalizeBlogLanguage(language = "en") {
  return String(language).toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function localizeBlogArticle(article, language = "en") {
  const normalizedLanguage = normalizeBlogLanguage(language);

  if (!article || normalizedLanguage !== "fr") {
    return article;
  }

  const translation = blogTranslationsFr[article.slug];

  if (!translation) {
    return article;
  }

  return {
    ...article,
    ...translation,
    sourceLinks: translation.sourceLinks || article.sourceLinks,
    sections: translation.sections || article.sections,
  };
}

export function getBlogArticles(language = "en") {
  return blogArticles.map((article) => localizeBlogArticle(article, language));
}

export const featuredBlogArticle = blogArticles[0];

export function getFeaturedBlogArticle(language = "en") {
  return localizeBlogArticle(featuredBlogArticle, language);
}

export function getBlogArticle(slug, language = "en") {
  const article = blogArticles.find((item) => item.slug === slug);

  return localizeBlogArticle(article, language);
}
